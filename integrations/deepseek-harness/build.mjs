// Generates client.js from src/client.src.js and the Doubao avatar project, so DeepSeek Harness runs
// the same avatar as Doubao, Codex, Yuanbao, the desktop pet and the Chrome extension:
//   __MODS__     the project's mods/*.js, each run as the watcher runs it
//   __CSS__      the project's mods/*.css
//   __ASSETS__   mods/assets pictures, as data URLs
//   __TOPICS__   topics.mjs (what the avatar needs of it)
//   __MEDIA__    the clip names in mods/media (media.js serves the clips from there),
//   __TRIMS__    and mods/media/trims.json, for the Host half to serve (media.js)
//   __APP__      where things are in DSH's window (src/dsh-page.mjs)
// The project is the doubaoProject folder (DOUBAO_PROJECT, else pet.js's DEFAULT_PROJECT).
// Run: node build.mjs (then restart DeepSeek Harness).
import fs from 'node:fs'
import { spawnSync } from 'node:child_process'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { DEFAULT_PROJECT } from './pet.js'
import { DSH_PAGE } from './src/dsh-page.mjs'

const root = path.dirname(fileURLToPath(import.meta.url))
const project = process.env.DOUBAO_PROJECT || DEFAULT_PROJECT
const MODS = path.join(project, 'mods')

if (!fs.existsSync(path.join(MODS, '30-avatar.js'))) {
  console.error(`The Doubao avatar project isn't at ${project} (set DOUBAO_PROJECT).`)
  process.exit(1)
}

// The avatar's page code, put together exactly as for the desktop apps and the browser extension
// (the project's avatar-bundle.mjs): pictures, topics, clip names, the topic rule, the start of each
// run, and each mod in its own function.
const bundle = await import(pathToFileURL(path.join(project, 'avatar-bundle.mjs')).href)
const loaded = await bundle.loadMods(project)
const mods = loaded.js
const assets = loaded.assets
const media = loaded.media

const source = fs.readFileSync(path.join(root, 'src', 'client.src.js'), 'utf8')
const fill = {
  __CONSTANTS__: bundle.constants(loaded, DSH_PAGE, { on: false, available: false }),
  __PRELUDE__: bundle.PRELUDE,
  __APPLY__: bundle.applyBlock(loaded, 'ai-avatar'),
}
let output = source
for (const [key, value] of Object.entries(fill)) {
  if (!output.includes(key)) throw new Error(`src/client.src.js has no ${key}`)
  output = output.replace(key, () => value)
}
const banner = '// Generated by build.mjs from src/client.src.js and the Doubao avatar project — edit those, then rebuild.\n'
// DSH reloads client.js as soon as it changes, so never let it see a half-written or broken file:
// write a temp file, check that it parses, then swap it in with one rename.
const temp = path.join(root, '.client.js.tmp.mjs')
fs.writeFileSync(temp, banner + output)
const check = spawnSync(process.execPath, ['--check', temp], { encoding: 'utf8' })
if (check.status !== 0) {
  fs.rmSync(temp, { force: true })
  console.error(`client.js NOT updated: the build doesn't parse, so DSH keeps the old one.\n${check.stderr}`)
  process.exit(1)
}
for (let tries = 0; ; tries++) {
  try { fs.renameSync(temp, path.join(root, 'client.js')); break } catch (error) {
    // Windows refuses the rename while DSH has the file open; that only lasts a moment.
    if (tries >= 20) { fs.rmSync(temp, { force: true }); throw error }
    Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 100)
  }
}
console.log(`client.js written (${(output.length / 1e6).toFixed(1)} MB): ${mods.map((m) => m.name).join(', ')}; `
  + `${Object.keys(assets).length} pictures, ${media.length} clips, from ${project}`)
