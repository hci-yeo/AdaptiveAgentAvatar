// Gathers what the Android app's avatar page needs into app/src/main/assets/web/, from the same
// sources as the desktop apps and the browser extension:
//   payload.js   the avatar (mods/30-avatar.js in pet mode, with its pictures), via avatar-bundle.mjs
//   rules.js     the topic rule (topic-rule.mjs) and the keyword lists (topics.mjs)
//   media/       the "Different people" walk clips (the other two styles would add ~110 MB)
//   lib/, models/, bank.*   the topic model and its engine, taken from the built browser extension
//   web-src/*    this app's own page files (index.html, glue.js, model.mjs, menu.*)
// and the app icon (the everyday expert's face) into res/mipmap-*.
//   node android/build-assets.mjs        (run `node browser-extension/build.mjs` first, once)
import { readdir, readFile, writeFile, mkdir, rm, cp, stat } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const OUT = join(HERE, 'app', 'src', 'main', 'assets', 'web');
const RES = join(HERE, 'app', 'src', 'main', 'res');
const EXT = join(ROOT, 'browser-extension', 'build', 'chrome');
const log = s => console.log(`[android] ${s}`);
const exists = p => stat(p).then(() => true, () => false);

if (!(await exists(join(EXT, 'models')))) {
  console.error('The browser extension is not built yet: run `node browser-extension/build.mjs` first.');
  process.exit(1);
}

const bundle = await import(pathToFileURL(join(ROOT, 'avatar-bundle.mjs')).href);
const mods = await bundle.loadMods(ROOT);
// Only the "Different people" style's clips (fish_ and single_ are the other two styles).
const media = mods.media.filter(f => !/^(fish|single)_/.test(f));

// The avatar, built as for the desktop pet window (watcher.mjs writePetPayload): only 30-avatar.js,
// no app stylesheet, APP id 'pet'.
const avatarOnly = { ...mods, css: '', media, js: mods.js.filter(m => m.name === '30-avatar.js') };
const app = { id: 'pet', pet: true, composer: null };
const payload = `// Generated by android/build-assets.mjs from mods/ - edit those, not this file.
(() => {${bundle.PRELUDE}${bundle.constants(avatarOnly, app, { on: true, available: true, chatMod: false })}
  const apply = () => {${bundle.applyBlock(avatarOnly, 'avatar')}};
  document.readyState === 'loading' ? document.addEventListener('DOMContentLoaded', apply, { once: true }) : apply();
})();
`;

// The topic rule as a plain script (the page's other scripts aren't modules), and the keyword lists.
const rule = mods.rule.replace(/^export /gm, '');
const rules = `// Generated by android/build-assets.mjs from topic-rule.mjs and topics.mjs - edit those.
window.TOPIC_RULE = (() => {
${rule}
return { rankTopics, resultOf, pickTopicWith, keywordTopic, keywordTopicOf, isCommand, MAX_QUESTIONS, MAX_CHARS };
})();
window.TOPIC_KW = ${JSON.stringify(mods.topics.map(({ outfit, zh, en }) => ({ outfit, zh, en })))};
`;

await rm(OUT, { recursive: true, force: true });
await mkdir(join(OUT, 'media'), { recursive: true });
await writeFile(join(OUT, 'payload.js'), payload);
await writeFile(join(OUT, 'rules.js'), rules);
for (const f of await readdir(join(HERE, 'web-src'))) await cp(join(HERE, 'web-src', f), join(OUT, f));
for (const f of media) await cp(join(ROOT, 'mods', 'media', f), join(OUT, 'media', f));
await cp(join(EXT, 'lib'), join(OUT, 'lib'), { recursive: true });
await cp(join(EXT, 'models'), join(OUT, 'models'), { recursive: true });
await cp(join(EXT, 'bank.json'), join(OUT, 'bank.json'));
await cp(join(EXT, 'bank.bin'), join(OUT, 'bank.bin'));
// A few experts' faces for the setup screen (settings.html).
await mkdir(join(OUT, 'img'), { recursive: true });
for (const who of ['casual', 'chef', 'doctor', 'programmer', 'astronaut'])
  await cp(join(ROOT, 'mods', 'assets', `expert-${who}.webp`), join(OUT, 'img', `${who}.webp`));

// App icon: the everyday expert's face, as on the extension.
const sharp = (await import('sharp')).default;
const face = join(ROOT, 'mods', 'assets', 'expert-casual.webp');
const meta = await sharp(face).metadata();
// A square from her top as wide as her middle part (550 of the 768 px height), so the wider
// pictures (Nov 2026) are framed like the old 550 px ones instead of zoomed out.
const side = Math.min(meta.width, Math.round(meta.height * 550 / 768));
for (const [dpi, size] of Object.entries({ mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 })) {
  const dir = join(RES, `mipmap-${dpi}`);
  await mkdir(dir, { recursive: true });
  const round = Buffer.from(`<svg width="${size}" height="${size}"><circle cx="${size / 2}" cy="${size / 2}" r="${size / 2}"/></svg>`);
  await sharp(face).extract({ left: Math.round((meta.width - side) / 2), top: 0, width: side, height: side })
    .resize(size, size).flatten({ background: '#f4f2fb' })
    .composite([{ input: round, blend: 'dest-in' }]).png().toFile(join(dir, 'ic_launcher.png'));
}

let total = 0;
const walk = async d => { for (const e of await readdir(d, { withFileTypes: true })) e.isDirectory() ? await walk(join(d, e.name)) : (total += (await stat(join(d, e.name))).size); };
await walk(OUT);
log(`done: ${OUT} (${(total / 1e6).toFixed(0)} MB, ${media.length} clips, ${Object.keys(mods.assets).length} pictures)`);
